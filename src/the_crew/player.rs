use std::{fmt, hash::BuildHasher};
use crate::the_crew::{Card, CardStack, PlayerId, Trick, mission::Mission};
use std::io::{self, Write};
use std::collections::HashSet;

pub enum CardInfo{
    Top,
    Single,
    Bottom
}
pub enum GameEvent {
    CardPlayed { by: PlayerId, card: Card },
    TrickWon { by: PlayerId },
    CardCommunicated{ by: PlayerId, card:Card, info:CardInfo},
}

pub struct PlayerView<'a>{
    pub m_id:PlayerId,
    pub m_is_captain:bool,
    pub m_hand:&'a CardStack, 
    pub m_has_communicated:bool,
    pub m_is_communicating:&'a Option<Card>,
    pub m_current_tick:&'a Option<Trick>
}
pub trait PlayerInterface{
    fn choose_mission(&self, view: &PlayerView, allowed: &Vec<usize>, missions: &Vec<Mission>) -> Vec<usize>;
    fn choose_card(&self, view: &PlayerView, legal: &[Card]) -> Card;
    fn notify(&mut self, view: &PlayerView, event: &GameEvent);
}
impl fmt::Debug for dyn PlayerInterface {
    fn fmt(&self, f: &mut fmt::Formatter) -> fmt::Result {
        write!(f,"")
    }
}
#[derive(Debug)]
pub struct Player{
    pub m_id:PlayerId,
    pub m_is_captain:bool,
    pub m_hand:CardStack,
    pub m_tricks:Vec<Trick>,
    pub m_has_communicated:bool,
    pub m_is_communicating:Option<Card>,
    pub interface: Box<dyn PlayerInterface>,
}
impl Player {
    pub fn to_view<'a>(&'a self, current_trick: &'a Option<Trick>) -> PlayerView<'a> {
        PlayerView {
            m_id: self.m_id,
            m_is_captain: self.m_is_captain,
            m_hand: &self.m_hand,
            m_has_communicated: self.m_has_communicated,
            m_is_communicating: &self.m_is_communicating,
            m_current_tick: current_trick,
        }
    }
    pub fn choose_mission(&self, view: &PlayerView, allowed: &Vec<usize>, missions: &Vec<Mission>) -> Vec<usize>{
        self.interface.choose_mission(view, allowed, missions)
    }
    pub fn choose_card(&self, view: &PlayerView, legal: &[Card]) -> Card{
        self.interface.choose_card(view, legal)
    }
    pub fn remove_card(&mut self, card:Card){
        let idx = self.m_hand.cards.iter().position(|&c| c == card)
            .expect("card must be in hand");
        self.m_hand.cards.remove(idx);
    }
}

// Terminal Interface mostly generated by claude, because I dont care about it
fn clear_terminal() {
    print!("\x1B[2J\x1B[1;1H");
    io::stdout().flush().unwrap();
}
pub struct TerminalInterface;

impl PlayerInterface for TerminalInterface {
    fn choose_card(&self, view: &PlayerView, legal: &[Card]) ->Card {
        let hand = view.m_hand;
            assert!(!hand.cards.is_empty(), "select_card called with an empty hand");
            loop {
                println!("Play a Card :)");
                for (i, card) in legal.iter().enumerate() {
                    print!("[{}] {:?}   ", i + 1, card);
                }
                println!();

                print!("Select a card (1-{}): ", legal.len());
                io::stdout().flush().unwrap();

                let mut input = String::new();
                match io::stdin().read_line(&mut input) {
                    Ok(0) => panic!("stdin closed"), // EOF, otherwise we'd loop forever
                    Ok(_) => {}
                    Err(_) => continue,
                }

                match input.trim().parse::<usize>() {
                    Ok(n) if (1..=hand.cards.len()).contains(&n) => {
                        clear_terminal();
                        return legal[n - 1];
                    }
                    _ => println!("Invalid choice, try again.\n"),
                }
            }
    }

    fn choose_mission(&self, view: &PlayerView, allowed: &Vec<usize>, missions:&Vec<Mission>) -> Vec<usize> {
            let total = missions.len();
            let picked = loop {
                println!("\nMissions:");
                for (i, m) in missions.iter().enumerate() {
                    match m.owned_by {
                        Some(o) => println!("  [{}] {} (taken by player {})", i + 1, m.description, o),
                        None => println!("  [{}] {}", i + 1, m.description),
                    }
                }
                let allowed_str: Vec<String> = allowed.iter().map(|a| a.to_string()).collect();
                print!(
                    "Player {}, choose {} mission(s) (numbers separated by spaces): ",
                    view.m_id,
                    allowed_str.join(" or ")
                );
                io::stdout().flush().unwrap();

                let mut input = String::new();
                match io::stdin().read_line(&mut input) {
                    Ok(0) => panic!("stdin closed"),
                    Ok(_) => {}
                    Err(_) => continue,
                }

                // Parse 1-based indices separated by spaces and/or commas.
                let parsed: Result<Vec<usize>, _> = input
                    .split(|c: char| c.is_whitespace() || c == ',')
                    .filter(|s| !s.is_empty())
                    .map(|s| s.parse::<usize>())
                    .collect();

                let indices = match parsed {
                    Ok(v) => v,
                    Err(_) => {
                        println!("Please enter numbers only.");
                        continue;
                    }
                };

                let unique: HashSet<usize> = indices.iter().copied().collect();
                if unique.len() != indices.len() {
                    println!("Duplicate selections.");
                    continue;
                }
                if !indices
                    .iter()
                    .all(|&i| i >= 1 && i <= total && missions[i - 1].owned_by.is_none())
                {
                    println!("Every number must refer to a mission that is still available.");
                    continue;
                }
                if !allowed.contains(&indices.len()) {
                    println!("You must choose {} mission(s).", allowed_str.join(" or "));
                    continue;
                }
                break indices;
            };
            picked
    }

    fn notify(&mut self, view: &PlayerView, event: &GameEvent) {
        view;
        event;
    }
}

