/* function generated by claude */
fn clear_terminal() {
    print!("\x1B[2J\x1B[1;1H");
    io::stdout().flush().unwrap();
}

/* function generated by claude */
fn select_card(hand: &CardStack) -> Card {
    assert!(!hand.cards.is_empty(), "select_card called with an empty hand");
    loop {
        println!("Play a Card :)");
        for (i, card) in hand.cards.iter().enumerate() {
            print!("[{}] {:?}   ", i + 1, card);
        }
        println!();

        print!("Select a card (1-{}): ", hand.cards.len());
        io::stdout().flush().unwrap();

        let mut input = String::new();
        match io::stdin().read_line(&mut input) {
            Ok(0) => panic!("stdin closed"), // EOF, otherwise we'd loop forever
            Ok(_) => {}
            Err(_) => continue,
        }

        match input.trim().parse::<usize>() {
            Ok(n) if (1..=hand.cards.len()).contains(&n) => {
                clear_terminal();
                return hand.cards[n - 1];
            }
            _ => println!("Invalid choice, try again.\n"),
        }
    }
}

